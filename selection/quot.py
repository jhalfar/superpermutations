"""quot.py - the (m, r) block divided by a group of relabellings (used by gsegip.py and lns_part.py).

The group is generated by the names in `sym`: old = rotation of the old letters 0 .. m-1, tok = cyclic shift of the
added letters, swap = exchange of the first two added letters.  It must act freely on the loops of the block; a
solution invariant under it is then given by what it does on one loop of every orbit.

    Quot(m, r, sym)
      .loops, .lset   the loops of the block (gcore.block_loops)
      .G, .scale      the group as a sorted list of relabellings (tuples), and its order
      .lrep           loop -> (representative loop of its orbit, index in G of the relabelling that maps it there)
      .lorb           the representative loops, in increasing order
      .states         all K rotations of every representative loop: one state per state orbit
      .rep_state(x)   the representative of the orbit of the state x
      .link(A, i)     the loop reached from the representative loop A when its letter A[i] steps forward over the
                      next letter
      .lift(ytypes)   an invariant solution on all loops from its rows on the state orbits

needs:    Python 3 and gcore.py.  Not a program of its own.
"""
from gcore import canon, block_loops


class Quot:
    """The block of m old and r added letters and its quotient by the group named in sym (see the header)."""

    def __init__(self, m, r, sym="old"):
        """Generate the group, find for every loop its representative and the relabelling that leads there."""
        self.m, self.r = m, r
        K = self.K = m + r
        self.loops = block_loops(m, r)
        self.lset = set(self.loops)
        gens = []
        for name in [x for x in sym.split(",") if x]:
            if name == "old":
                gens.append(tuple([(i + 1) % m for i in range(m)] + list(range(m, K))))
            elif name == "tok":
                gens.append(tuple(list(range(m)) + [m + (i + 1) % r for i in range(r)]))
            elif name == "swap":
                gens.append(tuple(list(range(m)) + [m + 1, m] + list(range(m + 2, K))))
            else:
                raise SystemExit("unknown symmetry " + name)
        G = {tuple(range(K))}
        fr = list(G)
        while fr:
            nf = []
            for g in fr:
                for h in gens:
                    x = tuple(h[c] for c in g)
                    if x not in G:
                        G.add(x)
                        nf.append(x)
            fr = nf
        self.G = sorted(G)
        # loop -> (representative loop, group element index that maps the loop to it)
        self.lrep = {}
        for L in self.loops:
            if L in self.lrep:
                continue
            imgs = [(canon(tuple(g[c] for c in L)), gi) for gi, g in enumerate(self.G)]
            orb = {}
            for M, gi in imgs:
                orb.setdefault(M, gi)
            assert len(orb) == len(self.G), "the group does not act freely on the loops"
            rep = min(orb)
            # element taking L to rep, then for every image M of L: element taking M to rep
            for M, gi in orb.items():
                # M = g_gi(L);  want h with h(M) = rep:  find by search (group is small)
                for hi, h in enumerate(self.G):
                    if canon(tuple(h[c] for c in M)) == rep:
                        self.lrep[M] = (rep, hi)
                        break
        self.lorb = sorted({v[0] for v in self.lrep.values()})
        self.scale = len(self.G)
        self.states = [A[rot:] + A[:rot] for A in self.lorb for rot in range(K)]

    def rep_state(self, x):
        """The state x carried into the representative loop of its orbit."""
        rep, hi = self.lrep[canon(x)]
        h = self.G[hi]
        return tuple(h[c] for c in x)

    def link(self, A, i):
        """A = representative loop, i = index of the mover c = A[i]: returns (B, i2): representative of the loop
        where c has stepped forward over its successor and the index of the (relabelled) mover there; None if the
        step transposes two old letters"""
        K = self.K
        j = (i + 1) % K
        if A[i] < self.m and A[j] < self.m:
            return None
        y = list(A)
        y[i], y[j] = y[j], y[i]
        cy = canon(tuple(y))
        rep, hi = self.lrep[cy]
        h = self.G[hi]
        return rep, rep.index(h[A[i]])

    def lift(self, ytypes):
        """ytypes: dict state orbit -> type of its row.  Returns the invariant solution on all loops of the block
        as dict loop -> (x, type); a loop that gets no row has (loop, "D")."""
        sel = {}
        for u, ty in ytypes.items():
            for g in self.G:
                x = tuple(g[c] for c in u)
                L = canon(x)
                assert L not in sel
                sel[L] = (x, ty)
        for L in self.loops:
            if L not in sel:
                sel[L] = (L, "D")
        return sel
