"""Write CATALOGUE.md from catalogue.jsonl (grouped by n; entries that need the owner listed separately).

    python3 catalogue/make_catalogue_md.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CAT = os.path.join(HERE, "catalogue.jsonl")
OUT = os.path.join(HERE, "CATALOGUE.md")

KIND_ORDER = ["lower-bound", "upper-construction", "class-optimum", "class-negative", "structural", "method-negative"]
KIND_TITLE = {
    "lower-bound": "Lower bounds", "upper-construction": "Constructions proved in Lean",
    "class-optimum": "Optimum of a class", "class-negative": "No word of a class", "structural": "Structure",
    "method-negative": "Methods that gave nothing",
}


def group_of(n):
    if n == "all":
        return (99, "every n")
    if isinstance(n, list):
        return (min(n), "n = " + ", ".join(str(x) for x in n))
    return (n, f"n = {n}")


def md(s):
    return s.replace("|", "\\|").replace("\n", " ")


def entry_md(e):
    pub = e["published"]
    lines = [
        f"#### `{e['id']}`",
        "",
        e["claim"],
        "",
        f"* status: **{e['status']}**; {'published: ' + pub['where'] if pub['yes'] else 'local, unpublished'}",
        f"* class: {e['family']}",
        f"* method: {e['method']}",
        f"* credit: {e['credit']}; date {e['date']}",
    ]
    rep = e["reproduce"]
    if rep["command"]:
        lines.append(f"* reproduce: `{rep['command']}` in `{rep['path'] or '.'}`")
    if e["evidence"]:
        lines.append("* evidence: " + "; ".join(
            f"`{ev['file']}`" + (f" (sha256 `{ev['sha256'][:12]}...`)" if ev["sha256"] else "") for ev in e["evidence"]))
    lines.append("* source: " + ", ".join(f"`{s}`" for s in e["source"]))
    if e["supersedes"]:
        lines.append("* supersedes: " + ", ".join(f"`{x}`" for x in e["supersedes"]))
    if e["superseded_by"]:
        lines.append("* superseded by: " + ", ".join(f"`{x}`" for x in e["superseded_by"]))
    if e.get("notes"):
        lines.append(f"* notes: {e['notes']}")
    if e["needs_owner"]:
        lines.append(f"* **needs owner:** {e['needs_owner']}")
    return "\n".join(lines) + "\n"


def main():
    with open(CAT, encoding="utf-8") as f:
        entries = [json.loads(x) for x in f if x.strip()]
    groups = {}
    for e in entries:
        groups.setdefault(group_of(e["n"]), []).append(e)
    counts = {}
    for e in entries:
        counts[e["status"]] = counts.get(e["status"], 0) + 1
    out = [
        "# Catalogue of results",
        "",
        "Generated by `make_catalogue_md.py` from `catalogue.jsonl`; do not edit by hand. The schema and the meaning",
        "of the statuses are in `schema.md`; `check_catalogue.py` validates the file.",
        "",
        f"{len(entries)} entries: " + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())) + ".",
        "",
        "| n | entries | lean | certificate | two programs | one program | conjecture |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for key in sorted(groups):
        es = groups[key]
        c = lambda s: sum(1 for e in es if e["status"] == s)  # noqa: E731
        out.append(f"| {key[1]} | {len(es)} | {c('lean')} | {c('certificate')} | {c('computed-two-programs')} | "
                   f"{c('computed-one-program')} | {c('conjecture')} |")
    owner = [e for e in entries if e["needs_owner"]]
    out += ["", "## Needs owner", ""]
    if owner:
        out += [f"* `{e['id']}`: {md(e['needs_owner'])}" for e in owner]
    else:
        out.append("None.")
    for key in sorted(groups):
        out += ["", f"## {key[1]}", ""]
        for kind in KIND_ORDER:
            es = [e for e in groups[key] if e["kind"] == kind]
            if not es:
                continue
            out += [f"### {KIND_TITLE[kind]}", ""]
            out += [entry_md(e) for e in es]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out).rstrip() + "\n")
    print(f"wrote {OUT}: {len(entries)} entries")


if __name__ == "__main__":
    main()
