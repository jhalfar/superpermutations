"""Writes Audit5901/NK7_<j>.lean and NK6_<jj>.lean: the Lean equations of K7 and K6 (fields k7, k6 of
K16.Evals) by native_decide, one theorem per file over a range of hash parts, so that an interrupted run loses
one file only.  K7: 64 parts at depth 8, 4 files of 16.  K6: 256 parts at depth 10, 16 files of 16."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = '''import LowerBounds.K16Search
import LowerBounds.K16Tables

/-!
# {tag} of Table C of 5,901, parts {pa} to {pb1} of {nt}: the Lean search equation by `native_decide`

Generated by `gen_nk.py` (agent pub5901).  As `NK.lean`: compiled with `--load-dynlib` of
`build/native/K16Search.dll` of the level-1 build; trusts the compiler, the C compiler, the runtime and the library.
Field `{field}` of `K16.Evals`: `Ev {tab} {s} {lo} {hi} 10 16 25 false`, fuel 400, {nt} parts by hash at depth {ds}.
-/

namespace SuperpermLowerBounds
namespace K16
namespace Audit

open T5901

theorem {name} : seqSearch 7 {tab} {s} {lo} {hi} 10 16 25 false 400 {ds} {nt} {pa} {pb} = false := by native_decide

end Audit
end K16
end SuperpermLowerBounds

#print axioms SuperpermLowerBounds.K16.Audit.{name}
'''
jobs = []
for tag, field, tab, s, lo, hi, ds, nt, per, pre in [
        ('K7', 'k7', 'Utab7', 7, 36, 54, 8, 64, 16, 'NK7_%d'),
        ('K6', 'k6', 'Utab6', 6, 38, 60, 10, 256, 16, 'NK6_%02d')]:
    for j in range(nt // per):
        pa, pb = j * per, (j + 1) * per
        mod = pre % j
        name = '%s_%d_%d' % (field, pa, pb)
        open(os.path.join(HERE, 'Audit5901', mod + '.lean'), 'w', newline='\n').write(HEAD.format(
            tag=tag, pa=pa, pb1=pb - 1, nt=nt, field=field, tab=tab, s=s, lo=lo, hi=hi, ds=ds, name=name, pb=pb))
        jobs.append(mod)
open(os.path.join(HERE, 'nk_order.txt'), 'w', newline='\n').write('\n'.join(jobs) + '\n')
print(len(jobs), 'files')
