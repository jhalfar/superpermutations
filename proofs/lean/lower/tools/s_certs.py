"""Write the Lean files that state the certificates.

usage: python s_certs.py [--force] [--suffix=X] NAME [NAME ...]        NAME = C<k>_<cn>_<bn>_<q>

  LowerBounds/SCertW.lean         S.WStatement k cn bn q   (chains of words; light imports)
  LowerBounds/SCertificates.lean  ModelStatement k cn bn q (model chains on Vtx k; imports SModel)

With --suffix=X the two files are SCertWX.lean and SCertificatesX.lean (the option was added for the package:
lower/build.sh uses it for the list of small certificates).

The fuel of each search is read from s_plan_<NAME>.log; a certificate is listed only if s_gen_<NAME>.log ends
with "done".  The bound in the comments is Theorem C's `boundC k cn bn q`, computed here for the reader only.
"""
import sys, os, re
from math import factorial
HERE = os.path.dirname(os.path.abspath(__file__))

def boundC(k, cn, bn, q):
    hpv = factorial(k) + factorial(k - 1) + factorial(k - 2) + k - 3
    pi = q * (k * k - 4 * k + 1) - cn * (k - 1)
    num = 2 * q * factorial(k - 2) - (2 * q * (k - 2) + bn)
    return hpv + (num + pi - 1) // pi

FORCE = "--force" in sys.argv          # list a certificate even if its build log does not end with "done"
SUF = "2" if "--second" in sys.argv else ""   # --second: write SCertW2.lean and SCertificates2.lean (later certificates)
for a in sys.argv[1:]:                        # --suffix=X: write SCertWX.lean and SCertificatesX.lean (a part of the list)
    if a.startswith("--suffix="): SUF = a[len("--suffix="):]
if SUF == "" and os.path.exists(os.path.join(HERE, "s_snapshot_frozen.flag")):
    raise SystemExit("SCertW.lean and SCertificates.lean belong to the release snapshot and are frozen; use --second")
certs = []
for name in [a for a in sys.argv[1:] if not a.startswith("--")]:
    m = re.fullmatch(r"C(\d+)_(\d+)_(\d+)_(\d+)", name)
    k, cn, bn, q = (int(x) for x in m.groups())
    log = open(os.path.join(HERE, f"s_gen_{name}.log")).read()
    if not FORCE and "done" not in log.splitlines()[-1]:
        print(f"{name}: not built, skipped"); continue
    first = open(os.path.join(HERE, f"s_plan_{name}.log")).readline()
    mm = re.match(r"search (\d+) (\d+) (\d+) (\d+) (\d+) (\d+) (\d+): \d+ states after the first piece, (\d+) calls", first)
    kk, A, q2, C1, C2, bn2, fuel, states = (int(x) for x in mm.groups())
    assert (kk, bn2) == (k, bn) and A == q * (k - 3) - cn and q2 == 2 * q
    certs.append(dict(name=name, k=k, cn=cn, bn=bn, q=q, A=A, q2=q2, C1=C1, C2=C2, fuel=fuel, states=states,
                      bound=boundC(k, cn, bn, q)))
certs.sort(key=lambda c: (c["k"], c["bound"], c["states"]))

def grp(n): return f"{n:,}"

w = ["""/-
Generated by s_certs.py.  Do not edit.
-/
import LowerBounds.SSound
import LowerBounds.SRun
""" + "".join(f"import LowerBounds.SGen.{c['name']}\n" for c in certs) + """
/-!
# Certificates: the window bound for chains of words

Each theorem is `S.wstatement_of_search` applied to a search that the kernel has evaluated in parts
(`LowerBounds/SGen/`) and to the run check (`SRun.lean`).  No `native_decide`.
-/

namespace SuperpermLowerBounds
"""]
for c in certs:
    t = "{k}_{cn}_{bn}_{q}".format(**c)
    w.append(f"""/-- `c = {c['cn']}/{c['q']}`, `b = {c['bn']}/{c['q']}` on {c['k']} symbols ({grp(c['states'])} states of the search).
Through Theorem C this gives the bound {grp(c['bound'])}. -/
theorem wstatement_{t} : S.WStatement {c['k']} {c['cn']} {c['bn']} {c['q']} :=
  S.wstatement_of_search (A := {c['A']}) (q2 := {c['q2']}) (C1 := {c['C1']}) (C2 := {c['C2']}) (fuel := {c['fuel']})
    (by decide) (by decide) (by decide) (by decide) (by decide) (by decide) (by decide)
    S.runSearch_{c['k']} SGen.search_{c['name']}
""")
w.append("end SuperpermLowerBounds\n")
open(os.path.join(HERE, "LowerBounds", f"SCertW{SUF}.lean"), "w", encoding="utf-8", newline="\n").write("\n".join(w))

m = ["""/-
Generated by s_certs.py.  Do not edit.
-/
import LowerBounds.SModel
import LowerBounds.SCertW""" + SUF + """

/-!
# Certificates: `ModelStatement k cn bn q`

Unconditional: every model chain on `k` symbols (`SModelDef.lean`) whose list of deficits is a
window satisfies `2 r + 2 (k - 4) + c δ ≤ (k - 3) δ + b` with `c = cn / q`, `b = bn / q`.
With `ModelStatement k cn bn q → HStatement k cn bn q` (the bridge to Liu's chains) each of them
turns Theorem C into the bound named in its comment.
-/

namespace SuperpermLowerBounds
"""]
for c in certs:
    t = "{k}_{cn}_{bn}_{q}".format(**c)
    m.append(f"""/-- `c = {c['cn']}/{c['q']}`, `b = {c['bn']}/{c['q']}` on {c['k']} symbols; Theorem C then gives {grp(c['bound'])}. -/
theorem modelStatement_{t} : ModelStatement {c['k']} {c['cn']} {c['bn']} {c['q']} :=
  modelStatement_of_wstatement wstatement_{t}
""")
m.append("end SuperpermLowerBounds\n")
open(os.path.join(HERE, "LowerBounds", f"SCertificates{SUF}.lean"), "w", encoding="utf-8", newline="\n").write("\n".join(m))

a = [f"import LowerBounds.SCertificates{SUF}\nopen SuperpermLowerBounds\n"]
for c in certs:
    a.append("#print axioms modelStatement_{k}_{cn}_{bn}_{q}".format(**c))
os.makedirs(os.path.join(HERE, "s_proto"), exist_ok=True)
open(os.path.join(HERE, "s_proto", f"AxCert{SUF}.lean"), "w", encoding="utf-8", newline="\n").write("\n".join(a) + "\n")
print(f"{len(certs)} certificates:")
for c in certs:
    print("  ModelStatement {k} {cn} {bn} {q}   bound {bound}   states {states}   fuel {fuel}".format(**c))
