"""Write the Lean file with the bounds of Theorem C without a hypothesis, numbers written out.

usage: python s_final.py [--out SFinal] [--certs SCertificates] [--skip FILE] [--suffix S] NAME [NAME ...]
       NAME = C<k>_<cn>_<bn>_<q>, a certificate of LowerBounds/<certs>.lean

For every k and every value of the bound the certificate with the smallest search is used.  With --skip FILE the
pairs (k, bound) that an earlier file already states (one "k bound" per line in FILE) are left out; the pairs
written are appended to s_final_<out>.pairs.  The file imports `LowerBounds.SBridgeTheoremC` (
`covers_length_ge_boundC_of_model`, `superperm_boundC_of_model`) and `LowerBounds.<certs>`.

Besides `covers_length_ge_N` and `ssuper_ge_N` for every bound N, the file has for every k the best bound of the
file under the plain names `covers_lower_bound_<k>` and `ssuper_lower_bound_<k>` (suffix `_b` in a later file, or
the suffix given with --suffix, an option added for the package), and prints their axioms.
"""
import sys, os, re
from math import factorial
HERE = os.path.dirname(os.path.abspath(__file__))

def boundC(k, cn, bn, q):
    hpv = factorial(k) + factorial(k - 1) + factorial(k - 2) + k - 3
    pi = q * (k * k - 4 * k + 1) - cn * (k - 1)
    num = 2 * q * factorial(k - 2) - (2 * q * (k - 2) + bn)
    return hpv + (num + pi - 1) // pi

argv = sys.argv[1:]
OUT, CERTS, SKIP, SUFFIX = "SFinal", "SCertificates", None, None
while argv and argv[0].startswith("--"):
    if argv[0] == "--out": OUT = argv[1]
    elif argv[0] == "--certs": CERTS = argv[1]
    elif argv[0] == "--skip": SKIP = argv[1]
    elif argv[0] == "--suffix": SUFFIX = argv[1]
    argv = argv[2:]
skip = set()
if SKIP:
    for line in open(os.path.join(HERE, SKIP)):
        if line.split(): skip.add(tuple(int(x) for x in line.split()[:2]))
SUF = "" if OUT == "SFinal" else "_b"
if SUFFIX is not None: SUF = SUFFIX
if OUT == "SFinal" and os.path.exists(os.path.join(HERE, "s_snapshot_frozen.flag")):
    raise SystemExit("SFinal.lean belongs to the release snapshot and is frozen; use --out SFinal2 --certs SCertificates2")

best = {}
for name in argv:
    m = re.fullmatch(r"C(\d+)_(\d+)_(\d+)_(\d+)", name)
    k, cn, bn, q = (int(x) for x in m.groups())
    first = open(os.path.join(HERE, f"s_plan_{name}.log")).readline()
    states = int(re.search(r"(\d+) calls", first).group(1))
    key = (k, boundC(k, cn, bn, q))
    if key in skip: continue
    if key not in best or states < best[key][0]:
        best[key] = (states, cn, bn, q)

out = [f"""/-
Generated by s_final.py.  Do not edit.
-/
import LowerBounds.SBridgeTheoremC
import LowerBounds.{CERTS}

/-!
# Lower bounds for superpermutations from Theorem C, without a hypothesis

For each certificate `ModelStatement k cn bn q` of `{CERTS}.lean` (a finite search evaluated by the
kernel): the three arithmetic conditions of Theorem C, the value of `boundC k cn bn q`, and the
bound itself in two forms,

* `covers_length_ge_N : ∀ w : List (Fin k), Covers w → N ≤ w.length` (every word over `k` symbols
  that contains every permutation of the symbols as a factor has at least `N` letters), and
* `ssuper_ge_N : N ≤ Ssuper k`.

At the end, for every `k`, the best bound of this file under a plain name
(`covers_lower_bound_k{SUF}`, `ssuper_lower_bound_k{SUF}`), with its axioms.

They follow from `covers_length_ge_boundC_of_model` and `superperm_boundC_of_model`
(`SBridgeTheoremC.lean`).  No `native_decide`.
-/

namespace SuperpermLowerBounds

open Hunter PreimageChain SuperpermutationBounds
"""]
for (k, N) in sorted(best):
    states, cn, bn, q = best[(k, N)]
    t = f"{k}_{cn}_{bn}_{q}"
    out.append(f"""/-! ### {k} symbols: {N:,} (`c = {cn}/{q}`, `b = {bn}/{q}`) -/

theorem conditionsC_{t} : ConditionsC {k} {cn} {bn} {q} := ⟨by decide, by decide, by decide, by decide⟩

theorem boundC_{t} : boundC {k} {cn} {bn} {q} = {N} := by decide

/-- Every word over {k} symbols that contains every permutation of the symbols as a factor has at
least {N:,} letters. -/
theorem covers_length_ge_{N} : ∀ w : List (Fin {k}), Covers w → {N} ≤ w.length :=
  boundC_{t} ▸ covers_length_ge_boundC_of_model (by decide) conditionsC_{t} modelStatement_{t}

/-- The shortest superpermutation on {k} symbols has at least {N:,} letters. -/
theorem ssuper_ge_{N} : {N} ≤ Ssuper {k} :=
  boundC_{t} ▸ superperm_boundC_of_model (by decide) conditionsC_{t} modelStatement_{t}
""")
out.append("/-! ### The best bound of this file for every number of symbols -/\n")
tops = {}
for (k, N) in best:
    if k not in tops or N > tops[k]: tops[k] = N
for k in sorted(tops):
    N = tops[k]
    out.append(f"""/-- Every word over {k} symbols that contains every permutation of the symbols as a factor has at
least {N:,} letters. -/
theorem covers_lower_bound_{k}{SUF} : ∀ w : List (Fin {k}), Covers w → {N} ≤ w.length :=
  covers_length_ge_{N}

/-- The shortest superpermutation on {k} symbols has at least {N:,} letters. -/
theorem ssuper_lower_bound_{k}{SUF} : {N} ≤ Ssuper {k} := ssuper_ge_{N}
""")
out.append("end SuperpermLowerBounds\n")
for k in sorted(tops):
    out.append(f"#print axioms SuperpermLowerBounds.covers_lower_bound_{k}{SUF}")
    out.append(f"#print axioms SuperpermLowerBounds.ssuper_lower_bound_{k}{SUF}")
open(os.path.join(HERE, "LowerBounds", f"{OUT}.lean"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
with open(os.path.join(HERE, f"s_final_{OUT}.pairs"), "w", newline="\n") as f:
    for (k, N) in sorted(best): f.write(f"{k} {N}\n")
ax = [f"import LowerBounds.{OUT}\nopen SuperpermLowerBounds\n"]
for (k, N) in sorted(best):
    ax.append(f"#print axioms covers_length_ge_{N}")
    ax.append(f"#print axioms ssuper_ge_{N}")
open(os.path.join(HERE, "s_proto", f"Ax{OUT}.lean"), "w", encoding="utf-8", newline="\n").write("\n".join(ax) + "\n")
for (k, N) in sorted(best):
    print(f"  k={k}: {N}  from {best[(k, N)][1:]}  ({best[(k, N)][0]} states)" + ("   <- best" if tops[k] == N else ""))
