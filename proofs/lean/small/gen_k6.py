"""gen_k6.py: writes K6/Tab.lean, the tables of the kernel search on 6 symbols, as Nat literals.

Words are the 720 permutations of 1..6 in the order of itertools.permutations (index 0 = 1 2 3 4 5 6).
  TP    18 bits per word: its six letters, 3 bits each, first letter highest
  TCI    7 bits: class index (classes numbered by their rotation that starts with 6, sorted)
  TNX   10 bits: the entry of the next block of a row (tau2: the door of the exit)
  TS3   50 bits: the five words that the exit of the block entered at the word overlaps in 3 letters, other class
  TREP  10 bits per class: the index of its rotation that starts with 6
  TROT   3 bits: s with (word).rotate s = the representative of its class
Nothing here is trusted: every fact the proofs use is checked against the words by `decide` in Lean.
"""
import itertools
import os
import sys

sys.set_int_max_str_digits(1000000)
K = 6
# the directory to write into (K6/ below it): the first argument, or the directory of this script
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))


def pack(vals, w):
    n = 0
    for i, v in enumerate(vals):
        assert 0 <= v < (1 << w), (v, w)
        n |= v << (w * i)
    return n


def build():
    perms = list(itertools.permutations(range(1, K + 1)))
    idx = {p: i for i, p in enumerate(perms)}

    def cls(p):
        i = p.index(K)
        return p[i:] + p[:i]

    cn = sorted({cls(p) for p in perms})
    cid = {c: i for i, c in enumerate(cn)}
    ci = [cid[cls(p)] for p in perms]
    exc = lambda p: p[-1:] + p[:-1]
    door = lambda x: x[2:] + (x[1], x[0])
    nx = [idx[door(exc(p))] for p in perms]
    s3 = []
    for p in perms:
        u = exc(p)
        lst = [idx[u[3:] + q] for q in itertools.permutations(u[:3]) if cls(u[3:] + q) != cls(p)]
        assert len(lst) == 5
        s3.extend(lst)
    rep = [idx[c] for c in cn]
    rot = []
    for p in perms:
        r = cls(p)
        s = next(s for s in range(K) if p[s:] + p[:s] == r)
        rot.append(s)
    tp = []
    for p in perms:
        x = 0
        for a in p:
            x = x * 8 + a
        tp.append(x)
    return perms, ci, nx, s3, rep, rot, tp


def main():
    perms, ci, nx, s3, rep, rot, tp = build()
    L = ["/-! Tables of the kernel search on 6 symbols (generated by `gen_k6.py`; see there). -/", "",
         "namespace K6", ""]
    L.append(f"def TP : Nat := {pack(tp, 18)}")
    L.append(f"def TCI : Nat := {pack(ci, 7)}")
    L.append(f"def TNX : Nat := {pack(nx, 10)}")
    L.append(f"def TS3 : Nat := {pack(s3, 10)}")
    L.append(f"def TREP : Nat := {pack(rep, 10)}")
    L.append(f"def TROT : Nat := {pack(rot, 3)}")
    L.append("")
    L.append("end K6")
    os.makedirs(os.path.join(OUT, "K6"), exist_ok=True)
    with open(os.path.join(OUT, "K6", "Tab.lean"), "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("identity index", perms.index(tuple(range(1, 7))))


if __name__ == "__main__":
    main()
