"""gen_tight.py: writes K6/TightTab.lean, the knapsack table of the tight case (defect 4) on 6 symbols.

TBT, 6 bits per entry, entry 21 n + g (n = 0..3 trails, g = 0..20 holes): the largest sum of W(h) - h over n
chains with g holes in all (W = the caps of gen_cap.py).  `TightRules.lean` checks it against the table `KT FO`
that Lean computes itself.
"""
import os
import sys

sys.set_int_max_str_digits(1000000)
# the directory to write into (K6/ below it): the first argument, or the directory of this script
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
W = [4, 4, 7, 7, 10, 10, 11, 13, 14, 15, 16, 17, 19, 19, 22, 23, 24, 25, 26, 27, 28]


def main():
    eW = [W[h] - h for h in range(21)]
    best = [[0] * 21]
    for n in range(1, 4):
        best.append([max(eW[x] + best[n - 1][g - x] for x in range(g + 1)) for g in range(21)])
    tbt = 0
    for n in range(4):
        for g in range(21):
            assert 0 <= best[n][g] < 64
            tbt |= best[n][g] << (6 * (21 * n + g))
    L = ["/-! The knapsack table of the tight case on 6 symbols (generated by `gen_tight.py`). -/", "",
         "namespace K6", "",
         f"def TBT : Nat := {tbt}", "", "end K6"]
    with open(os.path.join(OUT, "K6", "TightTab.lean"), "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    for n in range(4):
        print(n, best[n])


if __name__ == "__main__":
    main()
