"""gen_cap.py: writes K6/CapTab.lean, the chain caps W on 6 symbols and the rule tables of the chain search.

W (0..20 holes) = 4 4 7 7 10 10 11 13 14 15 16 17 19 19 22 23 24 25 26 27 28: the true caps M (from an
enumeration of all chains on 6 symbols) up to 14 holes, and h + 8 from 15 holes on (weaker than M there;
rows - holes <= 8 is all that the accounting needs, and the search for W is 52,386 nodes against 3.2 million
for M).
For levels lo..hi the rules are those of `PS.seqBad [W] 0 lo hi` and `PS.seqKeepN [W] 0 lo hi` at t = 0,
tabulated for r < 64 and d < 32 as bits 32 r + d.  `Cap.lean` checks the tables against the rules.
"""
import os
import sys

sys.set_int_max_str_digits(1000000)
# the directory to write into (K6/ below it): the first argument, or the directory of this script
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
W = [4, 4, 7, 7, 10, 10, 11, 13, 14, 15, 16, 17, 19, 19, 22, 23, 24, 25, 26, 27, 28]
LEVELS = [(0, 20)]


def cap(x):
    return W[x] if x < len(W) else 0


def tabs(lo, hi):
    tb = tk = 0
    for r in range(64):
        for d in range(32):
            if lo <= d <= hi and cap(d) < r:
                tb |= 1 << (32 * r + d)
            if any(lo <= x and d <= x and cap(x) < r + cap(x - d) for x in range(hi + 1)):
                tk |= 1 << (32 * r + d)
    return tb, tk


def main():
    L = ["/-! Chain caps on 6 symbols and the tables of the chain search (generated by `gen_cap.py`). -/", "",
         "namespace K6", "",
         "/-- Upper bounds for the rows of a chain on 6 symbols with 0 to 20 holes. -/",
         "def W6 : List Nat := [" + ", ".join(map(str, W)) + "]", ""]
    for lo, hi in LEVELS:
        tb, tk = tabs(lo, hi)
        L.append(f"/-- `seqBad [W6] 0 {lo} {hi} 0 r d` as bit `32 r + d`. -/")
        L.append(f"def TB_{lo}_{hi} : Nat := {tb}")
        L.append(f"/-- `seqKeepN [W6] 0 {lo} {hi} 0 r d` as bit `32 r + d`. -/")
        L.append(f"def TK_{lo}_{hi} : Nat := {tk}")
        L.append("")
    L.append("end K6")
    with open(os.path.join(OUT, "K6", "CapTab.lean"), "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
